"""Flavour themes: how book signals map to a cocktail profile.

Each `Theme` says which book signals point to it (goodbooks-10k genres, reader shelves, and
words in the title or description such as a setting or an era) and what it pours: weighted
cocktail words scored with the recipe search index, signature drinks of the style and the
glasses that serve it. The table is hand-written and tuned on the real 425 recipes and the
goodbooks-10k catalog; `tests/test_pairing_real_data.py` checks every signature drink exists.

Weights of the cocktail words are relative within a theme. Words cover ingredients ("bitters"
finds "Angostura Bitters"), recipe names ("toddy") and glasses ("flute"); alcohol-free
recipes are reached through the theme's `soft_terms` (coffee, tea, chocolate, fruit), used
only when the pairing must be alcohol-free, with a matching `soft_style`.

`LORE` adds a few well-documented literary drinks (the Vesper of Casino Royale, the gin
rickeys of The Great Gatsby) for books by their authors.
"""

from collections.abc import Mapping
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Theme:
    id: str
    label: str  # shown in reasons: "Your reading list leans Mystery and noir"
    style: str  # what it pours: "a bitter, spirit-forward whiskey drink"
    terms: Mapping[str, float]  # cocktail words and their weights
    # What it pours when only alcohol-free recipes are allowed (defaults to `style`), and the
    # extra words that find it (coffee, tea, fruit); they never count for alcoholic pairings.
    soft_style: str = ""
    soft_terms: Mapping[str, float] = field(default_factory=dict)
    genres: tuple[str, ...] = ()  # books.taxonomy.GENRES names
    shelves: tuple[str, ...] = ()  # reader shelves, as stored ("cozy mystery")
    words: tuple[str, ...] = ()  # lowercase words or phrases in the title or description
    signatures: tuple[str, ...] = ()  # catalog drink names that define the style
    glasses: tuple[str, ...] = ()  # catalog glass names that serve it
    # Words are places or eras ("mentions Paris"), not plot words.
    setting: bool = False
    # Scales every signal: broad themes ("Classics", "Adventure") weigh less than telling
    # ones, so a classic noir pours whiskey before sherry.
    strength: float = 1.0


@dataclass(frozen=True)
class Lore:
    """A drink tied to an author's books by the books themselves or by its own history."""

    author: str  # catalog spelling of the first author
    drink: str  # catalog drink name
    text: str


@dataclass(frozen=True)
class ThemeTable:
    themes: tuple[Theme, ...]
    fallback: Theme
    by_id: dict[str, Theme] = field(init=False)

    def __post_init__(self) -> None:
        object.__setattr__(self, "by_id", {t.id: t for t in (*self.themes, self.fallback)})


